"""Merge Porsche.exe and dx7z.dll dispatch tables into one sorted table."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sources = [
    root / "src/recomp/gen/recomp_dispatch.c",
    root / "src/recomp/dx7z/recomp_dispatch.c",
]
pat = re.compile(r"\{\s*(0x[0-9A-Fa-f]+)u,\s*([A-Za-z0-9_]+)\s*\}")
entries = []
for path in sources:
    text = path.read_text(encoding="utf-8", errors="replace")
    entries.extend(pat.findall(text))
entries = sorted(set(entries), key=lambda e: int(e[0], 16))
out = root / "src/recomp/recomp_dispatch.c"
decl = root / "src/recomp/recomp_decls.h"
lines = [
    "/* Merged dispatch: Porsche.exe + dx7z.dll. Generated by scripts/merge_dispatch.py */",
    '#include "recomp_types.h"',
    "",
]
decls = ["/* Generated declarations for every lifted function. */", "#pragma once", ""]
for addr, name in entries:
    decls.append(f"void {name}(void);")
    lines.append(f"void {name}(void);")
lines.append("")
lines.append("const recomp_dispatch_entry_t recomp_dispatch_table[] = {")
for addr, name in entries:
    lines.append(f"    {{ {addr}u, {name} }},")
lines.append("};")
lines.append(f"const uint32_t recomp_dispatch_count = {len(entries)};")
lines.append("")
out.write_text("\n".join(lines), encoding="utf-8")
decl.write_text("\n".join(decls) + "\n", encoding="utf-8")
print(f"merged {len(entries)} entries -> {out}")
