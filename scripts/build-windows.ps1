[CmdletBinding()]
param(
    [string]$LlvmMingw = $env:LLVM_MINGW,
    [string]$SDL3Root,
    [string]$SDL3TtfRoot,
    [string]$ExecutableName = 'PorscheUnleashed.exe',
    [switch]$BackendOnly,
    [switch]$TestBridge,
    [switch]$TestRuntime,
    [switch]$LegacyRenderer,
    [switch]$Rebuild
)
$ErrorActionPreference = 'Stop'
if ([IO.Path]::GetFileName($ExecutableName) -cne $ExecutableName -or -not $ExecutableName.EndsWith('.exe')) {
    throw 'ExecutableName must be a filename ending in .exe'
}
$taskRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
if (-not $LlvmMingw) {
    $LlvmMingw = 'C:\Games\NFS Porsche Unleashed\tools\llvm-mingw\llvm-mingw-20261020-msvcrt-x86_64'
}
if (-not $SDL3Root) {
    $SDL3Root = Join-Path $taskRoot 'third_party/sdl/SDL3-3.4.18/x86_64-w64-mingw32'
}
if (-not $SDL3TtfRoot) {
    $SDL3TtfRoot = Join-Path $taskRoot 'third_party/sdl/SDL3_ttf-3.2.2/x86_64-w64-mingw32'
}
$taskCompiler = Join-Path $LlvmMingw 'bin/clang.exe'
$taskPC = Join-Path $taskRoot 'third_party/pcrecomp'
$taskOut = Join-Path $taskRoot 'build/windows'
$taskObjDir = Join-Path $taskOut 'obj'
$taskUtf8 = [Text.UTF8Encoding]::new($false)

function Invoke-Compiler([string[]]$CompilerArgs) {
    & $taskCompiler @CompilerArgs
    if ($LASTEXITCODE -ne 0) { throw "clang failed (exit $LASTEXITCODE)" }
}
function Write-IfChanged([string]$Path, [string]$Content) {
    if (-not (Test-Path -LiteralPath $Path) -or [IO.File]::ReadAllText($Path) -cne $Content) {
        [IO.File]::WriteAllText($Path, $Content, $taskUtf8)
    }
}
function Copy-Runtime([string]$Source) {
    $taskDestination = Join-Path $taskOut ([IO.Path]::GetFileName($Source))
    # Loaded Windows DLLs cannot be overwritten. Identical dependencies need
    # no write, allowing standalone tests while the game is open.
    if (Test-Path -LiteralPath $taskDestination) {
        if ((Get-FileHash -LiteralPath $Source).Hash -ceq (Get-FileHash -LiteralPath $taskDestination).Hash) { return }
    }
    Copy-Item -LiteralPath $Source -Destination $taskDestination -Force
}
# Keep generated timestamps stable; no Python dependency for a desktop build.
function Merge-Dispatch {
    $taskEntries = @{}
    foreach ($taskSource in @('src/recomp/gen/recomp_dispatch.c', 'src/recomp/dx7z/recomp_dispatch.c')) {
        $taskText = [IO.File]::ReadAllText((Join-Path $taskRoot $taskSource))
        foreach ($taskMatch in [regex]::Matches($taskText, '\{\s*(0x[0-9A-Fa-f]+)u,\s*([A-Za-z0-9_]+)\s*\}')) {
            $taskAddress = [Convert]::ToUInt32($taskMatch.Groups[1].Value.Substring(2), 16)
            $taskName = $taskMatch.Groups[2].Value
            if ($taskEntries.ContainsKey($taskAddress) -and $taskEntries[$taskAddress] -cne $taskName) {
                throw "Conflicting dispatch functions at $($taskMatch.Groups[1].Value)"
            }
            $taskEntries[$taskAddress] = $taskName
        }
    }
    if ($taskEntries.Count -eq 0) { throw 'No lifted dispatch entries found' }
    $taskLines = [Collections.Generic.List[string]]::new()
    $taskDecls = [Collections.Generic.List[string]]::new()
    $taskLines.Add('/* Merged dispatch: Porsche.exe + dx7z.dll. Generated by scripts/merge_dispatch.py */')
    $taskLines.Add('#include "recomp_types.h"')
    $taskLines.Add('')
    $taskDecls.Add('/* Generated declarations for every lifted function. */')
    $taskDecls.Add('#pragma once')
    $taskDecls.Add('')
    $taskAddresses = @($taskEntries.Keys | Sort-Object)
    foreach ($taskAddress in $taskAddresses) {
        $taskLine = "void $($taskEntries[$taskAddress])(void);"
        $taskLines.Add($taskLine)
        $taskDecls.Add($taskLine)
    }
    $taskLines.Add('')
    $taskLines.Add('const recomp_dispatch_entry_t recomp_dispatch_table[] = {')
    foreach ($taskAddress in $taskAddresses) {
        $taskLines.Add(('    {{ 0x{0:X8}u, {1} }},' -f $taskAddress, $taskEntries[$taskAddress]))
    }
    $taskLines.Add('};')
    $taskLines.Add("const uint32_t recomp_dispatch_count = $($taskEntries.Count);")
    $taskLines.Add('')
    Write-IfChanged (Join-Path $taskRoot 'src/recomp/recomp_dispatch.c') ($taskLines -join "`n")
    Write-IfChanged (Join-Path $taskRoot 'src/recomp/recomp_decls.h') (($taskDecls -join "`n") + "`n")
}

if (-not (Test-Path -LiteralPath $taskCompiler)) { throw "Missing compiler: $taskCompiler" }
New-Item -ItemType Directory -Force -Path $taskOut, $taskObjDir | Out-Null
$taskOldPath = $env:PATH
$env:PATH = (Join-Path $LlvmMingw 'bin') + [IO.Path]::PathSeparator + $env:PATH
Push-Location -LiteralPath $taskRoot
try {
    if ($TestRuntime -and $TestBridge) { throw 'Use -TestRuntime or -TestBridge separately' }
    if ($TestBridge -and $LegacyRenderer) { throw '-TestBridge requires the SDL3 GPU backend' }
    if (-not $LegacyRenderer -and -not $TestRuntime -and -not (Test-Path -LiteralPath (Join-Path $taskRoot 'src/renderer/nfspu_shaders.h'))) {
        throw 'Missing generated shaders. Run npm ci --ignore-scripts, set DXC, then npm run shaders (see README.md).'
    }
    if (-not $LegacyRenderer -and -not $TestRuntime) {
        if (-not (Test-Path -LiteralPath (Join-Path $SDL3Root 'include/SDL3/SDL_gpu.h'))) {
            throw "Missing SDL3 development package: $SDL3Root. Run scripts/fetch-sdl3-windows.ps1 first."
        }
        $taskGpu = Join-Path $taskOut 'nfspu_gpu.dll'
        $taskGpuImport = Join-Path $taskOut 'libnfspu_gpu.dll.a'
        $taskGpuSources = @('src/renderer/nfspu_gpu.c','src/renderer/nfspu_gpu.h','src/renderer/nfspu_shaders.h',
            'src/renderer/graphics_overlay.c','src/renderer/graphics_overlay.h','src/renderer/graphics_options.h') |
            ForEach-Object { Get-Item -LiteralPath (Join-Path $taskRoot $_) }
        $taskGpuNewest = ($taskGpuSources | Sort-Object LastWriteTimeUtc | Select-Object -Last 1).LastWriteTimeUtc
        if ($Rebuild -or -not (Test-Path -LiteralPath $taskGpu) -or -not (Test-Path -LiteralPath $taskGpuImport) -or
            (Get-Item -LiteralPath $taskGpu).LastWriteTimeUtc -lt $taskGpuNewest) {
            Write-Host 'CC SDL3 GPU backend'
            Invoke-Compiler @('-shared', '-O2', '-std=c11', '-Wall', '-Wextra', "-I$SDL3Root/include", '-Isrc/renderer',
                'src/renderer/nfspu_gpu.c', 'src/renderer/graphics_overlay.c', '-o', $taskGpu, "-L$SDL3Root/lib", '-lSDL3', "-Wl,--out-implib,$taskGpuImport")
        }
        Write-Host 'CC SDL3 GPU smoke test'
        Invoke-Compiler @('-O2', '-std=c11', '-Isrc/renderer', 'src/renderer/gpu_smoke.c', '-o',
            (Join-Path $taskOut 'nfspu_gpu_smoke.exe'), "-L$taskOut", '-lnfspu_gpu')
        Copy-Runtime (Join-Path $SDL3Root 'bin/SDL3.dll')
    }
    if (-not $BackendOnly -or $TestBridge -or $TestRuntime) {
        if (-not $TestBridge -and -not $TestRuntime) {
            & (Join-Path $PSScriptRoot 'install-widescreen-hooks.ps1')
            Merge-Dispatch
        }
        $taskHeaderDirs = @('src/host', 'src/renderer', 'third_party/pcrecomp/runtime/recomp32', 'third_party/pcrecomp/runtime/win32hle')
        $taskHeaders = $taskHeaderDirs |
            ForEach-Object { Get-ChildItem -LiteralPath (Join-Path $taskRoot $_) -Recurse -Filter '*.h' -File }
        $taskNewestHeader = ($taskHeaders | Sort-Object LastWriteTimeUtc | Select-Object -Last 1).LastWriteTimeUtc
        # Generated code includes only the recomp32 headers and two forced
        # headers. A renderer/UI header edit must not rebuild the entire lift.
        $taskNewestGeneratedHeader = $taskNewestHeader
        if (-not $TestBridge -and -not $TestRuntime) {
            $taskGeneratedHeaders = @(Get-ChildItem -LiteralPath (Join-Path $taskPC 'runtime/recomp32') -Recurse -Filter '*.h' -File)
            $taskGeneratedHeaders += Get-Item -LiteralPath (Join-Path $taskRoot 'src/recomp/recomp_decls.h'), (Join-Path $taskRoot 'src/host/win_posix.h')
            $taskNewestGeneratedHeader = ($taskGeneratedHeaders | Sort-Object LastWriteTimeUtc | Select-Object -Last 1).LastWriteTimeUtc
        }
        $taskCommon = @('-O1', '-std=c11', '-w', '-fno-strict-aliasing', '-fwrapv', '-DRECOMP_MEM_BASE=0x100000000000ull',
            '-include', (Join-Path $taskRoot 'src/host/win_posix.h'),
            "-I$taskPC/runtime/recomp32", "-I$taskPC/runtime/win32hle", '-Isrc/host', '-Isrc/host/wincompat',
            '-Isrc/recomp/gen', '-Isrc/recomp/dx7z', '-Isrc/renderer', "-I$SDL3Root/include", "-I$SDL3TtfRoot/include")
        $taskSources = @('src/host/thrash.c', 'src/host/widescreen.c', 'src/host/hud_layout.c', 'src/host/win_mman.c', 'src/host/win_socket.c')
        if ($TestRuntime) {
            $taskSources = @('src/host/runtime_thread_test.c', 'src/host/win_mman.c')
        } elseif ($TestBridge) {
            $taskSources += 'src/host/thrash_bridge_test.c'
        } else {
            $taskSources += @('src/host/main.c', 'src/host/dinput.c', 'src/host/game_shims.c', 'src/recomp/recomp_dispatch.c')
        }
        $taskHle = 'advapi32 bink ddraw dsound gdi32 gdidc guest_mem hle_path host host_lite kernel32 kernel32_crt kernel32_ext lz32 module mss ole32 pe_loader present screen storage user32 winmm wsock32'
        if ($TestRuntime) { $taskHle = 'host_lite guest_mem' }
        $taskSources += @($taskHle.Split(' ') | ForEach-Object { "third_party/pcrecomp/runtime/win32hle/$_.c" })
        if (-not $TestBridge -and -not $TestRuntime) {
            $taskSources += @(Get-ChildItem src/recomp/gen/recomp_*.c, src/recomp/dx7z/recomp_*.c |
                Where-Object { $_.Name -ne 'recomp_dispatch.c' } | ForEach-Object { $_.FullName })
        }
        $taskObjects = [Collections.Generic.List[string]]::new()
        foreach ($taskSource in $taskSources) {
            $taskSourcePath = if ([IO.Path]::IsPathRooted($taskSource)) {
                [IO.Path]::GetFullPath($taskSource)
            } else {
                [IO.Path]::GetFullPath((Join-Path $taskRoot $taskSource))
            }
            $taskObjectName = ($taskSourcePath -replace '[\\/:]', '_') + '.o'
            $taskObject = Join-Path $taskObjDir $taskObjectName
            $taskFlags = @($taskCommon)
            $taskGenerated = $taskSourcePath -match '[\\/]src[\\/]recomp[\\/](gen|dx7z)[\\/]'
            $taskRelevantHeaderStamp = $taskNewestHeader
            if ($taskGenerated) {
                $taskFlags += @('-O0', '-include', (Join-Path $taskRoot 'src/recomp/recomp_decls.h'))
                $taskRelevantHeaderStamp = $taskNewestGeneratedHeader
            }
            $taskSignature = ($taskCompiler, (Get-Item -LiteralPath $taskCompiler).LastWriteTimeUtc.Ticks, ($taskFlags -join "`0")) -join "`n"
            $taskCommandFile = $taskObject + '.command'
            $taskNeedsCompile = $Rebuild -or -not (Test-Path -LiteralPath $taskObject) -or -not (Test-Path -LiteralPath $taskCommandFile)
            if (-not $taskNeedsCompile) {
                $taskObjStamp = (Get-Item -LiteralPath $taskObject).LastWriteTimeUtc
                $taskNeedsCompile = $taskObjStamp -lt (Get-Item -LiteralPath $taskSourcePath).LastWriteTimeUtc -or
                    $taskObjStamp -lt $taskRelevantHeaderStamp -or [IO.File]::ReadAllText($taskCommandFile) -cne $taskSignature
            }
            if ($taskNeedsCompile) {
                Write-Host "CC $taskSource"
                Invoke-Compiler ($taskFlags + @('-c', $taskSourcePath, '-o', $taskObject))
                [IO.File]::WriteAllText($taskCommandFile, $taskSignature, $taskUtf8)
            }
            $taskObjects.Add($taskObject)
        }
        $taskExecutable = if ($TestRuntime) { 'nfspu_runtime_test.exe' } elseif ($TestBridge) { 'nfspu_thrash_test.exe' } else { $ExecutableName }
        Write-Host "Linking $taskExecutable"
        $taskLinkFlags = if ($TestRuntime) { @('-lpthread') } else { @("-L$SDL3Root/lib", "-L$SDL3TtfRoot/lib", '-lSDL3', '-lSDL3_ttf', '-lpthread', '-lws2_32', '-Wl,--stack,16777216') }
        Invoke-Compiler (@('-o', (Join-Path $taskOut $taskExecutable)) + $taskObjects.ToArray() +
            $taskLinkFlags)
        if (-not $TestRuntime) {
            Get-ChildItem -LiteralPath (Join-Path $SDL3Root 'bin'), (Join-Path $SDL3TtfRoot 'bin') -Filter '*.dll' -File |
                ForEach-Object { Copy-Runtime $_.FullName }
        }
    }
    Copy-Runtime (Join-Path $LlvmMingw 'bin/libwinpthread-1.dll')
    if ($TestBridge -or $TestRuntime) {
        $taskTestLabel = if ($TestRuntime) { 'runtime-test' } else { 'thrash-test' }
        Push-Location -LiteralPath $taskOut
        try {
            $taskTest = Start-Process -FilePath (Join-Path $taskOut $taskExecutable) -WorkingDirectory $taskOut -WindowStyle Hidden -PassThru `
                -RedirectStandardOutput (Join-Path $taskOut "$taskTestLabel.log") -RedirectStandardError (Join-Path $taskOut "$taskTestLabel-errors.log")
            # Retain a native handle before a short test exits; Windows
            # PowerShell otherwise sometimes leaves Process.ExitCode null.
            $null = $taskTest.Handle
            if (-not $taskTest.WaitForExit(30000)) {
                Stop-Process -Id $taskTest.Id -ErrorAction SilentlyContinue
                throw "$taskTestLabel timed out after 30 seconds"
            }
            $taskTest.WaitForExit()
            Get-Content -LiteralPath (Join-Path $taskOut "$taskTestLabel.log"), (Join-Path $taskOut "$taskTestLabel-errors.log")
            if ($taskTest.ExitCode -ne 0) { throw "$taskTestLabel failed (exit $($taskTest.ExitCode))" }
        } finally { Pop-Location }
    }
    Write-Host "Built outputs in $taskOut"
} finally {
    Pop-Location
    $env:PATH = $taskOldPath
}
